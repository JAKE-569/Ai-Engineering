create extension if not exists vector with schema extensions;

create table if not exists public.engineering_rules (
  id bigint generated by default as identity primary key,
  code text not null,
  clause text,
  content text not null,
  trade text,
  source_url text,
  publisher text,
  embedding extensions.vector(2048) not null,
  created_at timestamptz not null default now()
);

-- NVIDIA nemotron-3-embed-1b returns 2048 dimensions.
-- pgvector ivfflat indexes support at most 2000 dimensions, so the initial
-- implementation uses exact cosine ordering without an incompatible index.
-- Add a halfvec/dimension-reduction index later when the corpus grows.

create or replace function public.match_engineering_rules(
  query_embedding extensions.vector(2048),
  match_trade text default null,
  match_count integer default 5
)
returns table (
  id bigint,
  code text,
  clause text,
  content text,
  trade text,
  source_url text,
  publisher text,
  similarity real
)
language sql stable
as $$
  select r.id, r.code, r.clause, r.content, r.trade, r.source_url, r.publisher,
         (1 - (r.embedding <=> query_embedding))::real as similarity
  from public.engineering_rules r
  where match_trade is null or r.trade = match_trade or r.trade = '공통'
  order by r.embedding <=> query_embedding
  limit greatest(match_count, 1);
$$;

revoke all on function public.match_engineering_rules(extensions.vector(2048), text, integer) from public;
grant execute on function public.match_engineering_rules(extensions.vector(2048), text, integer) to service_role;
