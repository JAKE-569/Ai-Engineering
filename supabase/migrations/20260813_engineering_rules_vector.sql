-- Canonical schema and migration. Apply manually in Supabase; no remote changes are made by the app.
create schema if not exists extensions;
create extension if not exists vector with schema extensions;
set search_path = public, extensions;
create table if not exists public.engineering_rules (
 id bigint generated by default as identity primary key,
 code text not null, clause text, content text not null, trade text,
 source_url text, publisher text, embedding vector(2048),
 created_at timestamptz not null default now()
);
alter table public.engineering_rules add column if not exists chunk_key text;
alter table public.engineering_rules add column if not exists source_status text;
update public.engineering_rules set trade = case
    when code ~ '^NF(P|T)C' then '소방'
    when code = 'KDS 11 10 05' then '토목'
    when code = 'KDS 57 65 00' then '토목'
    when code = 'KDS 21 30 00' then '토목'
    when code = '건축법 시행령 제34조·제35조' then '건축'
    when code = '건축법 시행령 제46조' then '건축'
    when code = '장애인등편의법' then '건축'
    when code = 'KDS 31 25 10' then '건축기계'
    when code = 'KDS 31 30 15' then '건축기계'
    when code = '기계설비법 시행규칙' then '건축기계'
    when code = 'KEC 140·142' then '건축전기'
    when code = 'KEC 232' then '건축전기'
    when code = 'KEC 351·352' then '건축전기'
    else coalesce(trade, '공통') end;
update public.engineering_rules set source_status = case when code ~ '^NF(P|T)C' then 'EXCERPT' else 'SUMMARY' end where source_status is null;
update public.engineering_rules set chunk_key = md5(code || chr(31) || coalesce(clause, '') || chr(31) || content) where chunk_key is null;
-- Only exact duplicate chunks are removed; distinct clauses remain.
delete from public.engineering_rules a using public.engineering_rules b
 where a.id > b.id and a.chunk_key = b.chunk_key and a.code = b.code and a.clause is not distinct from b.clause and a.content = b.content;
create unique index if not exists engineering_rules_chunk_key on public.engineering_rules(chunk_key);
-- 2048-dimensional vector indexes exceed the vector HNSW limit. Use exact search.
drop index if exists public.engineering_rules_embedding_hnsw;
drop function if exists public.match_engineering_rules(vector, text, integer);
create function public.match_engineering_rules(query_embedding vector(2048), match_trade text default null, match_count integer default 5)
returns table(id bigint, code text, clause text, content text, trade text, source_url text, publisher text, source_status text, similarity double precision)
language sql stable security invoker set search_path = public, extensions as $$
 select r.id, r.code, r.clause, r.content, r.trade, r.source_url, r.publisher, r.source_status,
 (1 - (r.embedding <=> query_embedding))::double precision
 from public.engineering_rules r
 where r.embedding is not null and r.source_status <> 'SOURCE_ONLY'
 and (match_trade is null or r.trade = match_trade or r.trade = '공통')
 order by r.embedding <=> query_embedding limit greatest(1, least(match_count, 100));
$$;
alter table public.engineering_rules enable row level security;
revoke all on function public.match_engineering_rules(vector, text, integer) from public;
grant execute on function public.match_engineering_rules(vector, text, integer) to service_role;
grant select, insert, update on public.engineering_rules to service_role;
grant usage, select on sequence public.engineering_rules_id_seq to service_role;
